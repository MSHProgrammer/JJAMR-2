export function getDetectiveRank(totalPoints: number) {
  let current = DETECTIVE_RANKS[0];
  let next = DETECTIVE_RANKS[1] || null;
  for (let i = 0; i < DETECTIVE_RANKS.length; i++) {
    if (totalPoints >= DETECTIVE_RANKS[i].minPoints) {
      current = DETECTIVE_RANKS[i];
      next = DETECTIVE_RANKS[i + 1] || null;
    }
  }
  return { current, next };
}

