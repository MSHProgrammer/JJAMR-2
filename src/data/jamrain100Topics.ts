// Generate 60 questions per topic (20 at 200, 20 at 400, 20 at 600) => 6,000 questions
export function buildDefault6000Questions(): Question[] {
  const result: Question[] = [];
  const pointsTiers: Array<200 | 400 | 600> = [200, 400, 600];

  ALL_RAW_SPECS.slice(0, 100).forEach((spec, tIdx) => {
    for (let i = 0; i < 60; i++) {
      const tier = pointsTiers[Math.floor(i / 20)];
      const fact = spec.facts[i];
      if (fact) {
        result.push({
          id: `q_${spec.id}_${i + 1}`,
          topicId: spec.id,
          points: tier,
          question: fact.q,
          answer: fact.a,
          hint: fact.hint,
        });
      } else {
        const filler = EXTRA_FILLER_BANK[(i + tIdx * 3) % EXTRA_FILLER_BANK.length];
        result.push({
          id: `q_${spec.id}_${i + 1}`,
          topicId: spec.id,
          points: tier,
          question: filler.q.replace('{T}', spec.name),
          answer: filler.a,
          hint: filler.hint,
        });
      }
    }
  });

  return result;
}
